// ---- ID helpers --------------------------------------------------------------

const ids = <T extends string>(prefix: string, list: readonly (readonly [string, ...unknown[]])[]): Record<string, T> => {
  const out: Record<string, T> = {};
  list.forEach((row, i) => {
    out[row[0] as string] = `${prefix}_${i + 1}` as T;
  });
  return out;
};

